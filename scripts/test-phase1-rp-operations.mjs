import assert from 'node:assert/strict';
import { createRpOperations } from './phase1-rp-operations.mjs';
const tracker = createRpOperations({ settleTimeoutMs: 100 });
tracker.register('private-state-a'); tracker.register('private-state-b');
const a = tracker.begin('private-state-a'), b = tracker.begin('private-state-b');
let settledA = false;
a.addEventListener('abort', () => setTimeout(() => { settledA = true; tracker.complete('private-state-a', { stage: 'token', kind: 'timeout', status: null }); }, 10), { once: true });
const finishA = tracker.finish('private-state-a', { abort: true, reason: 'timeout' });
const finishB = tracker.finish('private-state-b');
setTimeout(() => tracker.complete('private-state-b', { stage: 'replay', kind: 'http', status: 429 }), 5);
assert.deepEqual(await finishB, { stage: 'replay', kind: 'http', status: 429 });
assert.equal(b.aborted, false);
assert.deepEqual(await finishA, { stage: 'token', kind: 'timeout', status: null });
assert.equal(settledA, true); assert.equal(tracker.size(), 0);
tracker.register('never-started');
assert.equal(tracker.canStart('never-started'), true);
assert.deepEqual(await tracker.finish('never-started', { abort: true, reason: 'timeout' }), { stage: 'callback', kind: 'timeout', status: null });
assert.equal(tracker.canStart('never-started'), false);
assert.throws(() => tracker.begin('never-started'), /Unknown RP operation/);
tracker.register('stuck'); tracker.begin('stuck');
assert.deepEqual(await tracker.finish('stuck', { abort: true, reason: 'timeout' }), { stage: 'callback', kind: 'unsettled', status: null });
tracker.complete('stuck', { stage: 'token', kind: 'http', status: 500 });
assert.equal(tracker.size(), 0);
console.log('Concurrent callback cancellation and bounded settlement remain scoped and sanitized.');
