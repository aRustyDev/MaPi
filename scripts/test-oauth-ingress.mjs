import assert from "node:assert/strict";
import { handleOAuthIngress, isOAuthRoute } from "../worker/oauth-ingress.js";

const origin = "https://issuer.example", project = "proj_test";
let calls = 0, last;
const object = { async oauthRequest(request) {
  calls++; last = request;
  return { status: 303, headers: { location: ["https://rp.example/callback"], "set-cookie": ["a=1; Path=/", "b=2; Path=/"], "cache-control": ["public"], "x-private": ["omit"] }, body: "" };
} };
const send = (path, options = {}) => handleOAuthIngress(new Request(origin + path, options), object, project, origin);
assert.ok(isOAuthRoute("GET", `/oauth/${project}/authorize`, project));
assert.equal(isOAuthRoute("GET", `/oauth/${project}/.well-known/openid-configuration`, project), false);
assert.equal(isOAuthRoute("GET", "/oauth/proj_other/authorize", project), false);
let response = await send(`/oauth/${project}/authorize?client_id=client`);
assert.equal(response.status, 303);
assert.equal(response.headers.get("cache-control"), "no-store");
assert.equal(response.headers.getSetCookie().length, 2);
assert.equal(response.headers.get("x-private"), null);
response = await send(`/oauth/${project}/token`, { method: "POST", headers: { authorization: "Basic test", "content-type": "application/x-www-form-urlencoded" }, body: "grant_type=authorization_code" });
assert.equal(response.status, 303);
assert.equal(last.headers.authorization[0], "Basic test");
const before = calls;
assert.equal((await send("/oauth/continue", { method: "POST", body: "x" })).status, 403);
assert.equal((await send("/oauth/continue", { method: "POST", headers: { origin: "https://evil.example" }, body: "x" })).status, 403);
assert.equal((await send(`/oauth/${project}/token`, { method: "POST", headers: { origin: "https://evil.example" }, body: "x" })).status, 403);
assert.equal((await send(`/oauth/${project}/.well-known/openid-configuration`)).status, 404);
assert.equal((await send(`/oauth/${project}/authorize?${"a".repeat(8193)}`)).status, 403);
assert.equal((await send(`/oauth/${project}/token`, { method: "POST", body: "x".repeat(65537) })).status, 413);
assert.equal(calls, before);
console.log("OAuth ingress allowlist, origin, body limit and response handling passed.");
