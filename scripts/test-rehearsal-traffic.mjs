import assert from 'node:assert/strict';
import { createRehearsalTraffic, classifyClosure } from './rehearsal-traffic.mjs';
import { drainBounded } from './rehearsal-body.mjs';

const id = 'a'.repeat(32), fixture = { state: 'prepared', rehearsalId: id, origin: `https://mapi-p1-rehearsal-${id}-owner.synthetic.workers.dev`, otherOrigin: `https://mapi-p1-rehearsal-${id}-router.synthetic.workers.dev`, email: 'a@example.test', otherEmail: 'b@example.test', password: 'private', cookie: 'source=secret' };
const requests = [];
const fetcher = async (url, options) => {
  requests.push({ origin: url.origin, path: url.pathname, options });
  if (url.origin === fixture.origin) return new Response(null, { status: 503 });
  return new Response(null, { status: url.pathname === '/login' ? 303 : 200, headers: url.pathname === '/login' ? { 'set-cookie': 'other=secret; Path=/' } : {} });
};
const traffic = createRehearsalTraffic(fixture, { fetcher });
await assert.rejects(traffic.sample(), /setup missing/);
await traffic.prepare();
const sample = await traffic.sample({ requireClosed: true });
assert.equal(sample.sourceLogin.status, 503);
assert.equal(sample.sourceSession.status, 503);
assert.equal(sample.otherLogin.status, 303);
assert.equal(sample.otherSession.status, 200);
assert.equal(requests.length, 5);
assert.equal(requests[1].options.body.get('email'), fixture.email);
assert.equal(requests[3].options.body.get('email'), fixture.otherEmail);
assert.equal(requests[4].options.headers.cookie, 'other=secret');
assert.ok(!JSON.stringify(sample).includes('secret'));
assert.throws(() => createRehearsalTraffic({ ...fixture, origin: 'https://existing.workers.dev' }), /generated synthetic/);
assert.throws(() => createRehearsalTraffic({ ...fixture, otherOrigin: fixture.origin }), /generated synthetic|distinct/);
const bad = createRehearsalTraffic(fixture, { fetcher: async (url, options) => options.method === 'POST' && url.origin === fixture.otherOrigin ? new Response(null, { status: 303, headers: { 'set-cookie': 'other=secret' } }) : new Response(null, { status: 401 }) });
await bad.prepare();
await assert.rejects(bad.sample({ requireClosed: true }), /traffic failed/);
const unexpectedlyOpen = createRehearsalTraffic(fixture, { fetcher: async (url, options) => options.method === 'POST' ? new Response(null, { status: 303, headers: { 'set-cookie': 'synthetic=secret' } }) : new Response(null, { status: 200 }) });
await unexpectedlyOpen.prepare();
await assert.rejects(unexpectedlyOpen.sample({ requireClosed: true }), /Moving project traffic returned unexpected status/);
await assert.rejects(unexpectedlyOpen.sample(), /Moving project traffic returned unexpected status/);
assert.equal(classifyClosure('importing', 'reconciling'), 'fenced');
assert.equal(classifyClosure('reconciling', 'committed'), 'cutover-boundary-excluded');
assert.throws(() => classifyClosure('committed', 'retired'), /outside fenced/);
assert.throws(() => classifyClosure('importing', 'retired'), /Unexpected coordinator/);
const controller = new AbortController();
assert.equal(await drainBounded(new Response('small'), controller, 5), 5);
await assert.rejects(drainBounded(new Response('oversized'), controller, 5), /byte limit/);
assert.equal(controller.signal.aborted, true);
let requestNumber = 0, settleRemaining;
const release = new Promise(resolve => { settleRemaining = resolve; });
const pendingResponses = [];
const settleTraffic = createRehearsalTraffic(fixture, { fetcher: async () => {
  requestNumber++;
  if (requestNumber === 1) return new Response(null, { status: 303, headers: { 'set-cookie': 'other=secret' } });
  if (requestNumber === 2) throw Error('injected login failure');
  await release;
  const response = new Response('drain me', { status: 200 });
  pendingResponses.push(response);
  return response;
} });
await settleTraffic.prepare();
let settled = false;
const failingSample = settleTraffic.sample().then(() => { settled = true; throw Error('Expected sample failure'); }, error => { settled = true; return error; });
await new Promise(resolve => setImmediate(resolve));
assert.equal(requestNumber, 5, 'All four sample requests must start');
assert.equal(settled, false, 'Sample must await the other requests after a failure');
settleRemaining();
assert.match((await failingSample).message, /injected login failure/);
assert.equal(pendingResponses.length, 3);
assert.ok(pendingResponses.every(response => response.bodyUsed), 'Every remaining response must be drained');
console.log('Synthetic traffic scope, maintenance classification, isolation failure and secret-free results passed.');
